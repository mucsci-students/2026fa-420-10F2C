#!/usr/bin/env bash
# AI chat upgrade (Sprint 3), applied ON TOP of add-ai-schedule-generation.sh:
#   * the chat is kept on the server, so it is still there after a page change or reload
#   * "New chat", a chat picker and Delete (several chats per browser)
#   * the page behind the chat updates in place after the assistant changes something (no refresh)
# Keep this script OUTSIDE the repo.
#
#   bash ~/add-ai-chat-persistence.sh          # NO_TEST=1 skips the test run
#
# All-or-nothing: if any file does not match, nothing is changed.
# The payload below is gzip+base64 text, so editors/transfers cannot corrupt it.
set -euo pipefail

root=$(git rev-parse --show-toplevel 2>/dev/null) || { echo "Run this inside the repo."; exit 1; }
cd "$root"
branch=$(git branch --show-current)
case "$branch" in develop|main|master) echo "You are on '$branch'. Use your feature branch."; exit 1;; esac
if [ -e gui/ai/chats.py ]; then echo "Already applied (gui/ai/chats.py exists). Nothing to do."; exit 0; fi
[ -f gui/ai/generation.py ] || { echo "Run add-ai-schedule-generation.sh first (gui/ai/generation.py is missing)."; exit 1; }

work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
sed -n '/^#__PAYLOAD_BELOW__/,$p' "$0" | tail -n +2 | tr -d '\r \t' | base64 -d | gunzip > "$work/p.patch" \
  || { echo "The payload in this script is damaged; re-download it."; exit 1; }

if ! git apply --check "$work/p.patch" 2> "$work/err"; then
  echo "Your files differ from what this script expects (the state right after add-ai-schedule-generation.sh), so nothing was changed:"
  cat "$work/err"; exit 1
fi
git apply "$work/p.patch"
echo "Applied. Changed files:"; git status --short

if [ "${NO_TEST:-0}" != "1" ] && command -v uv >/dev/null 2>&1; then
  uv run pytest tests/test_ai_chats.py tests/test_ai_generation.py tests/test_ai_chat.py tests/test_ai_tools.py tests/test_ai_changes.py tests/test_ai_langchain.py tests/test_gui_chat.py -q
fi
exit 0
