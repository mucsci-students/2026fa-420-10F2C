#!/usr/bin/env bash
# Adds AI schedule generation to the chat assistant (Sprint 3).
# Built against develop bc68df6. Keep this script OUTSIDE the repo.
#
#   git checkout develop && git pull
#   git checkout -b feature/ai-schedule-generation
#   bash ~/add-ai-schedule-generation.sh          # NO_TEST=1 skips the test run
#
# All-or-nothing: if any file does not match, nothing is changed.
# The payload below is gzip+base64 text, so editors/transfers cannot corrupt it.
set -euo pipefail

root=$(git rev-parse --show-toplevel 2>/dev/null) || { echo "Run this inside the repo."; exit 1; }
cd "$root"
branch=$(git branch --show-current)
case "$branch" in develop|main|master) echo "You are on '$branch'. Create a feature branch first."; exit 1;; esac
if [ -e gui/ai/generation.py ]; then echo "Already applied (gui/ai/generation.py exists). Nothing to do."; exit 0; fi
[ -f gui/ai/changes.py ] || { echo "This does not look like the right project/branch (gui/ai/changes.py missing)."; exit 1; }

work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
sed -n '/^#__PAYLOAD_BELOW__/,$p' "$0" | tail -n +2 | tr -d '\r \t' | base64 -d | gunzip > "$work/p.patch" \
  || { echo "The payload in this script is damaged; re-download it."; exit 1; }

if ! git apply --check "$work/p.patch" 2> "$work/err"; then
  echo "The files differ from develop bc68df6, so nothing was changed:"; cat "$work/err"; exit 1
fi
git apply "$work/p.patch"
echo "Applied. Changed files:"; git status --short

if [ "${NO_TEST:-0}" != "1" ] && command -v uv >/dev/null 2>&1; then
  uv run pytest tests/test_ai_generation.py tests/test_ai_chat.py tests/test_ai_tools.py tests/test_ai_changes.py tests/test_ai_langchain.py tests/test_gui_chat.py -q
fi
exit 0
