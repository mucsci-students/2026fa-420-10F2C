#!/usr/bin/env bash
# Smarter AI assistant (Sprint 3 follow-up), applied ON TOP of add-ai-chat-persistence.sh:
#   * part of a name is enough ("delete room 136" finds Roddy 136), "Did you mean ...?" for near misses
#   * undo / redo / history, so "put the room we deleted back" works (also a one-click "Undo the last change")
#   * a failed run says what is probably wrong and what you changed last; "check my configuration" does too
#   * several requests in one message ("put the room back, then generate a schedule")
# Keep this script OUTSIDE the repo.
#
#   bash ~/add-ai-smarter-assistant.sh          # NO_TEST=1 skips the test run
#
# All-or-nothing: if any file does not match, nothing is changed.
set -euo pipefail

root=$(git rev-parse --show-toplevel 2>/dev/null) || { echo "Run this inside the repo."; exit 1; }
cd "$root"
branch=$(git branch --show-current)
case "$branch" in develop|main|master) echo "You are on '$branch'. Use your feature branch."; exit 1;; esac
if [ -e gui/ai/undo.py ]; then echo "Already applied (gui/ai/undo.py exists). Nothing to do."; exit 0; fi
[ -f gui/ai/chats.py ] || { echo "Run add-ai-chat-persistence.sh first (gui/ai/chats.py is missing)."; exit 1; }

work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
sed -n '/^#__PAYLOAD_BELOW__/,$p' "$0" | tail -n +2 | tr -d '\r \t' | base64 -d | gunzip > "$work/p.patch" \
  || { echo "The payload in this script is damaged; re-download it."; exit 1; }

if ! git apply --check "$work/p.patch" 2> "$work/err"; then
  echo "Your files differ from what this script expects, so nothing was changed:"; cat "$work/err"; exit 1
fi
git apply "$work/p.patch"
echo "Applied. Changed files:"; git status --short

if [ "${NO_TEST:-0}" != "1" ] && command -v uv >/dev/null 2>&1; then
  uv run pytest tests/test_ai_smarter.py tests/test_ai_chats.py tests/test_ai_generation.py tests/test_ai_chat.py tests/test_ai_tools.py tests/test_ai_changes.py tests/test_ai_langchain.py tests/test_gui_chat.py -q
fi
exit 0
